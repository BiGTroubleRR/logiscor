const ISO_3166_1_ALPHA_2 = new Set(ISO_3166_1_ALPHA_2_CODES);

// Matches 2+ consecutive uppercase 2-letter tokens joined by hyphens/commas (with optional
// spaces around the separator), e.g. "CZ-AT-IT-SI" or "DE, AT, HU".
const LANE_PATTERN = /\b([A-Z]{2}(?:\s*[-,]\s*[A-Z]{2})+)\b/g;

export function extractLaneCodes(description: string): string[] {
  const found = new Set<string>();
  const matches = description.match(LANE_PATTERN) ?? [];
  matches.forEach((group) => {
    group.split(/[-,]/).forEach((token) => {
      const code = token.trim();
      if (ISO_3166_1_ALPHA_2.has(code)) found.add(code);
    });
  });
  return Array.from(found);
}
